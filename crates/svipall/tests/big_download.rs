//! A download past 4 GiB, streamed to disk, cut past the 4 GiB mark and resumed.
//!
//! The size that breaks a download path is the one a 32-bit offset cannot hold: a length, a range
//! start or a byte count kept in a `u32` somewhere wraps at 4 GiB, and every test with a file of a
//! few hundred kilobytes passes regardless. Nothing that size is kept in the repository or in
//! memory: the local server below makes each byte from its offset as it sends it, answers `Range`
//! and `If-Range` against a strong ETag, and cuts the first transfer just past 4 GiB. The test then
//! checks the file's length, its checksum (computed here over the same generated bytes, on another
//! thread, while the download runs), sample bytes on both sides of the 4 GiB mark, and that this
//! process never held more than a small fraction of the file in memory.
//!
//! Minutes, not seconds, in a debug build (each byte is hashed by the download, again when the
//! resume reads back what is on disk, and once more here), so it is run by hand:
//! `cargo test -p svipall --test big_download -- --ignored --nocapture`. The 4+ GiB file is
//! deleted when the test ends, passed or failed.
mod support;

use sha2::{Digest, Sha256};
use std::path::PathBuf;
use svipall::{server::SvipallServer, tools::WebFetchParams};
use tokio::io::{AsyncReadExt, AsyncWriteExt};

const GIB: u64 = 1 << 30;
/// Past 4 GiB by 64 MiB and an odd 7 bytes, so no boundary lines up with anything.
const SIZE: u64 = 4 * GIB + 64 * (1 << 20) + 7;
/// Where the first transfer is cut: past the 4 GiB mark.
const CUT: u64 = 4 * GIB + (1 << 20) + 3;
const BLOCK: u64 = 1 << 16;
const ETAG: &str = "\"big-v1\"";

/// The 64 KiB block every block is made from: the block index in its first eight bytes, then a
/// fixed pattern that is not text, so the file is a binary download.
fn block(index: u64) -> Vec<u8> {
    let mut b: Vec<u8> = (0..BLOCK)
        .map(|i| (i.wrapping_mul(2_654_435_761) >> 13) as u8)
        .collect();
    b[..8].copy_from_slice(&index.to_le_bytes());
    b
}

/// The bytes `[from, to)` of the file, a block at a time.
fn bytes(from: u64, to: u64, mut each: impl FnMut(&[u8])) {
    let mut at = from;
    while at < to {
        let index = at / BLOCK;
        let b = block(index);
        let start = (at % BLOCK) as usize;
        let end = (BLOCK.min(to - index * BLOCK)) as usize;
        each(&b[start..end]);
        at = index * BLOCK + end as u64;
    }
}

fn byte_at(offset: u64) -> u8 {
    block(offset / BLOCK)[(offset % BLOCK) as usize]
}

fn header<'a>(head: &'a str, name: &str) -> Option<&'a str> {
    head.lines().find_map(|l| {
        let (k, v) = l.split_once(':')?;
        k.trim().eq_ignore_ascii_case(name).then(|| v.trim())
    })
}

/// The generating server. Returns its port.
async fn serve() -> u16 {
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let port = listener.local_addr().unwrap().port();
    let served = std::sync::Arc::new(std::sync::atomic::AtomicUsize::new(0));
    tokio::spawn(async move {
        loop {
            let Ok((mut sock, _)) = listener.accept().await else {
                return;
            };
            let nth = served.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
            tokio::spawn(async move {
                let mut buf = Vec::new();
                let mut chunk = [0u8; 2048];
                while !buf.windows(4).any(|w| w == b"\r\n\r\n") {
                    match sock.read(&mut chunk).await {
                        Ok(0) | Err(_) => return,
                        Ok(n) => buf.extend_from_slice(&chunk[..n]),
                    }
                }
                let head = String::from_utf8_lossy(&buf).to_string();
                let start = header(&head, "range")
                    .and_then(|r| r.strip_prefix("bytes="))
                    .and_then(|r| r.strip_suffix('-'))
                    .and_then(|r| r.parse::<u64>().ok())
                    .filter(|_| header(&head, "if-range").is_none_or(|v| v == ETAG));
                let (status, from) = match start {
                    Some(s) => ("206 Partial Content", s),
                    None => ("200 OK", 0),
                };
                let mut out = format!(
                    "HTTP/1.1 {status}\r\nContent-Type: application/octet-stream\r\n\
                     Content-Length: {}\r\nETag: {ETAG}\r\nAccept-Ranges: bytes\r\n\
                     Connection: close\r\n",
                    SIZE - from
                );
                if start.is_some() {
                    out.push_str(&format!(
                        "Content-Range: bytes {from}-{}/{SIZE}\r\n",
                        SIZE - 1
                    ));
                }
                out.push_str("\r\n");
                if sock.write_all(out.as_bytes()).await.is_err() {
                    return;
                }
                // The first transfer hangs up past 4 GiB, as a dropped connection would.
                let to = if nth == 0 { CUT } else { SIZE };
                let mut at = from;
                while at < to {
                    let mut piece = Vec::with_capacity(BLOCK as usize);
                    bytes(at, (at + BLOCK).min(to), |b| piece.extend_from_slice(b));
                    if sock.write_all(&piece).await.is_err() {
                        return;
                    }
                    at += piece.len() as u64;
                }
                let _ = sock.flush().await;
            });
        }
    });
    port
}

/// The most memory this process has committed so far, in bytes.
#[cfg(windows)]
fn peak_memory() -> u64 {
    #[repr(C)]
    #[derive(Default)]
    struct Counters {
        cb: u32,
        page_fault_count: u32,
        peak_working_set_size: usize,
        working_set_size: usize,
        quota_peak_paged_pool_usage: usize,
        quota_paged_pool_usage: usize,
        quota_peak_non_paged_pool_usage: usize,
        quota_non_paged_pool_usage: usize,
        pagefile_usage: usize,
        peak_pagefile_usage: usize,
    }
    extern "system" {
        fn GetCurrentProcess() -> isize;
        fn K32GetProcessMemoryInfo(process: isize, counters: *mut Counters, cb: u32) -> i32;
    }
    let mut c = Counters {
        cb: std::mem::size_of::<Counters>() as u32,
        ..Default::default()
    };
    // SAFETY: the pseudo-handle needs no closing, and `c` is a correctly sized, writable struct.
    let ok = unsafe { K32GetProcessMemoryInfo(GetCurrentProcess(), &mut c, c.cb) };
    assert!(ok != 0, "the memory counters could not be read");
    c.peak_pagefile_usage.max(c.peak_working_set_size) as u64
}

#[cfg(not(windows))]
fn peak_memory() -> u64 {
    // VmHWM: the peak resident set, in kB.
    std::fs::read_to_string("/proc/self/status")
        .ok()
        .and_then(|s| {
            s.lines()
                .find(|l| l.starts_with("VmHWM:"))
                .and_then(|l| l.split_whitespace().nth(1)?.parse::<u64>().ok())
        })
        .map(|kb| kb * 1024)
        .unwrap_or(0)
}

/// The download and what it left, removed however the test ends.
struct Cleanup(PathBuf);

impl Drop for Cleanup {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn hex(d: &[u8]) -> String {
    d.iter().map(|b| format!("{b:02x}")).collect()
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "writes a 4 GiB file and takes minutes; run by hand"]
async fn a_download_past_4_gib_streams_to_disk_and_resumes_past_the_mark() {
    let home = support::isolate();
    let dir = home.join("big");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let _cleanup = Cleanup(dir.clone());
    let target = dir.join("big.bin");
    let reference = std::thread::spawn(|| {
        let mut h = Sha256::new();
        bytes(0, SIZE, |b| h.update(b));
        hex(&h.finalize())
    });

    let port = serve().await;
    let server = SvipallServer::new(
        None,
        svipall_core::Config {
            request_min_interval_ms: 1,
            max_tier: "http".into(),
            ..Default::default()
        },
        None,
    );
    let params = || WebFetchParams {
        url: format!("http://127.0.0.1:{port}/big.bin"),
        cache: Some("bypass".into()),
        robots: Some("ignore".into()),
        out_file: Some(target.to_string_lossy().into_owned()),
        timeout: Some(3_600_000),
        ..Default::default()
    };
    let started = std::time::Instant::now();
    let first = server.fetch_json(params()).await.value;
    println!("first, after {:?}: {first}", started.elapsed());
    assert_eq!(first["file"]["partial"], true, "{first}");
    assert_eq!(first["file"]["resumable"], true, "{first}");
    assert_eq!(first["file"]["bytes_written"], CUT, "{first}");
    assert_eq!(first["file"]["expected_bytes"], SIZE, "{first}");
    let part = PathBuf::from(format!("{}.part", target.display()));
    assert_eq!(std::fs::metadata(&part).unwrap().len(), CUT);

    let second = server.fetch_json(params()).await.value;
    println!("second, after {:?}: {second}", started.elapsed());
    assert_eq!(second["status"], 206, "{second}");
    assert_eq!(second["file"]["resumed_from"], CUT, "{second}");
    assert_eq!(second["file"]["complete"], true, "{second}");
    assert_eq!(second["file"]["bytes"], SIZE, "{second}");
    assert_eq!(std::fs::metadata(&target).unwrap().len(), SIZE);
    assert!(!part.exists());

    // Bytes on both sides of the 4 GiB mark and of the cut, read back from disk.
    {
        use std::io::{Read, Seek, SeekFrom};
        let mut f = std::fs::File::open(&target).unwrap();
        for at in [0, 4 * GIB - 1, 4 * GIB, 4 * GIB + 1, CUT - 1, CUT, SIZE - 1] {
            let mut b = [0u8; 1];
            f.seek(SeekFrom::Start(at)).unwrap();
            f.read_exact(&mut b).unwrap();
            assert_eq!(b[0], byte_at(at), "byte {at}");
        }
    }

    let want = reference.join().unwrap();
    assert_eq!(second["file"]["sha256"], want, "{second}");

    let peak = peak_memory();
    println!(
        "peak memory {} MiB for a {} MiB file; {:?} in all",
        peak >> 20,
        SIZE >> 20,
        started.elapsed()
    );
    assert!(
        peak < 1 << 30,
        "the process peaked at {} MiB: the body was held in memory",
        peak >> 20
    );
}
